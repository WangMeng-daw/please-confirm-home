from pathlib import Path
import hashlib,json,re
root=Path(__file__).resolve().parent
for page in ['index.html','game.html']:
    p=root/page
    if p.exists():
        html=p.read_text(encoding='utf-8')
        html=re.sub(r'((?:src|href)="([^"?]+\.(?:js|css))\?v=)[^"]+',lambda m:m[1]+hashlib.sha256((root/m[2]).read_bytes()).hexdigest()[:10] if (root/m[2]).exists() and m[2]!='resource-manifest.js' else m[0],html)
        p.write_text(html,encoding='utf-8')

# All first-party browser resources, except the already self-contained portable
# file and server/config/docs. Stable hashes allow reuse across cache versions.
files=sorted([p for p in root.iterdir() if p.suffix in ['.js','.css'] and p.name not in ['resource-manifest.js','resource-sw.js']]+[root/'index.html',root/'game.html']+[p for p in (root/'assets').iterdir() if p.suffix in ['.png','.webp']])
entries=[]
for p in files:
    data=p.read_bytes();digest=hashlib.sha256(data).hexdigest()
    entries.append({'path':p.relative_to(root).as_posix(),'hash':digest,'bytes':len(data)})
version=hashlib.sha256(json.dumps(entries,sort_keys=True).encode()).hexdigest()[:16]
manifest={'version':version,'cacheName':'confirm-home-resources-'+version,'totalBytes':sum(e['bytes'] for e in entries),'entries':entries}
(root/'resource-manifest.js').write_text('/* Generated by work/build-launch.py; no private configuration. */\nself.HOME_RESOURCE_MANIFEST='+json.dumps(manifest,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({'resources':len(entries),'bytes':manifest['totalBytes'],'version':version}))
